// The monthly report PDF (pdf-lib, same tooling and Xocks header as the
// commission invoice in lib/pdf/generate-statement.ts). Three pages in the
// approved layout: headline numbers and store bands (page 1), the action plan
// (page 2), store lists and new stores (page 3). Sections that run past the
// bottom of a page continue on a new page, so long lists never clip.

import { PDFDocument, PDFFont, PDFPage, rgb, StandardFonts } from 'pdf-lib'
import { dayLabel } from './months'
import { round2, type ActionCard, type MonthlyReport, type ReportStore, type ActionTone } from './compute'

const PAGE_W = 595
const PAGE_H = 842
const MX = 40
const CW = PAGE_W - MX * 2
const HEADER_H = 64
const BOTTOM = 60

const C = {
  black: rgb(0.05, 0.05, 0.05),
  ink: rgb(0.1, 0.1, 0.1),
  grey: rgb(0.4, 0.4, 0.4),
  faint: rgb(0.6, 0.6, 0.6),
  yellow: rgb(1, 0.85, 0.1),
  white: rgb(1, 1, 1),
  card: rgb(0.96, 0.96, 0.96),
  track: rgb(0.9, 0.9, 0.9),
  green: rgb(0.12, 0.55, 0.24),
  amber: rgb(0.78, 0.45, 0.02),
  red: rgb(0.8, 0.13, 0.13),
  greenTint: rgb(0.9, 0.96, 0.91),
  amberTint: rgb(1, 0.96, 0.85),
  redTint: rgb(0.99, 0.91, 0.91),
}

const TONE = {
  green: { solid: C.green, tint: C.greenTint },
  amber: { solid: C.amber, tint: C.amberTint },
  red: { solid: C.red, tint: C.redTint },
} as const

type Font = PDFFont

/** "RM2,464.41" */
export function fmtRM(n: number): string {
  const [whole, frac] = round2(Math.abs(n)).toFixed(2).split('.')
  const commas = whole.replace(/\B(?=(\d{3})+(?!\d))/g, ',')
  return `${n < 0 ? '-' : ''}RM${commas}.${frac}`
}

function plural(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? '' : 's'}`
}

class Sheet {
  readonly pages: PDFPage[] = []
  private page!: PDFPage
  private subtitle = ''
  y = 0

  constructor(
    private readonly doc: PDFDocument,
    readonly regular: Font,
    readonly bold: Font,
    private readonly report: MonthlyReport,
  ) {}

  /** Starts a page with the Xocks header. */
  newPage(subtitle: string) {
    this.subtitle = subtitle
    this.page = this.doc.addPage([PAGE_W, PAGE_H])
    this.pages.push(this.page)
    this.page.drawRectangle({ x: 0, y: PAGE_H - HEADER_H, width: PAGE_W, height: HEADER_H, color: C.black })
    this.text('XCMS Monthly Report', MX, PAGE_H - 34, { size: 20, font: this.bold, color: C.yellow })
    this.text(subtitle, MX, PAGE_H - 51, { size: 9, color: C.white })
    this.rightText(this.report.monthLabel, PAGE_W - MX, PAGE_H - 30, { size: 11, font: this.bold, color: C.yellow })
    this.rightText(`Generated ${dayLabel(this.report.today)}`, PAGE_W - MX, PAGE_H - 45, { size: 7.5, color: C.faint })
    this.y = PAGE_H - HEADER_H - 26
  }

  /** Moves to a new page when `h` points no longer fit above the footer. */
  ensure(h: number) {
    if (this.y - h < BOTTOM) this.newPage(this.subtitle)
  }

  text(s: string, x: number, y: number, o: { size?: number; font?: Font; color?: ReturnType<typeof rgb> } = {}) {
    this.page.drawText(s, { x, y, size: o.size ?? 9, font: o.font ?? this.regular, color: o.color ?? C.ink })
  }

  rightText(s: string, rightX: number, y: number, o: { size?: number; font?: Font; color?: ReturnType<typeof rgb> } = {}) {
    const size = o.size ?? 9
    const font = o.font ?? this.regular
    this.text(s, rightX - font.widthOfTextAtSize(s, size), y, o)
  }

  width(s: string, size: number, font: Font = this.regular): number {
    return font.widthOfTextAtSize(s, size)
  }

  /** Truncates with an ellipsis so the text fits in maxW. */
  fit(s: string, maxW: number, size: number, font: Font = this.regular): string {
    if (this.width(s, size, font) <= maxW) return s
    let t = s
    while (t.length > 1 && this.width(`${t}…`, size, font) > maxW) t = t.slice(0, -1)
    return `${t}…`
  }

  rect(x: number, y: number, w: number, h: number, color: ReturnType<typeof rgb>) {
    this.page.drawRectangle({ x, y, width: w, height: h, color })
  }

  /** Up or down triangle, `size` wide and high, top-left at (x, yTop). */
  arrow(x: number, yTop: number, dir: 'up' | 'down' | 'flat', color: ReturnType<typeof rgb>) {
    if (dir === 'flat') {
      this.rect(x, yTop - 2, 7, 1.5, color)
      return
    }
    const path = dir === 'up' ? 'M 3.5 0 L 7 6 L 0 6 Z' : 'M 0 0 L 7 0 L 3.5 6 Z'
    this.page.drawSvgPath(path, { x, y: yTop, color })
  }

  finish() {
    const total = this.pages.length
    this.pages.forEach((p, i) => {
      p.drawText(`Sales = ${this.report.periodLabel}. Stock levels as of ${dayLabel(this.report.today)}. Generated by XCMS.`, {
        x: MX, y: 28, size: 7.5, font: this.regular, color: C.grey,
      })
      const label = `Page ${i + 1} of ${total}`
      p.drawText(label, { x: PAGE_W - MX - this.regular.widthOfTextAtSize(label, 7.5), y: 28, size: 7.5, font: this.regular, color: C.grey })
    })
  }
}

// ── Page 1 ──────────────────────────────────────────────────────────────────

function compareText(cur: number, prev: number, prevShort: string, fmt: (n: number) => string, unit: 'count' | 'money' | 'pairs') {
  const diff = cur - prev
  const dir = diff > 0 ? 'up' as const : diff < 0 ? 'down' as const : 'flat' as const
  if (dir === 'flat') return { text: `no change vs ${prevShort}`, dir }
  // Counts read as "1 vs Aug (14)"; money and pairs as a percentage.
  if (prev === 0) {
    const change = unit === 'money' ? fmt(Math.abs(diff)) : String(Math.abs(diff))
    return { text: `${change} vs ${prevShort} (${fmt(prev)})`, dir }
  }
  if (unit === 'count') return { text: `${Math.abs(diff)} vs ${prevShort} (${prev})`, dir }
  const pct = (Math.abs(diff) / prev) * 100
  return { text: `${pct.toFixed(1)}% vs ${prevShort} (${fmt(prev)})`, dir }
}

function drawHeadline(s: Sheet, r: MonthlyReport) {
  const h = r.headline
  const money = (n: number) => fmtRM(n)
  const cards: Array<{ label: string; value: string; delta?: { text: string; dir: 'up' | 'down' | 'flat' }; note?: { text: string; tone: ActionTone } }> = [
    { label: 'Active stores', value: String(h.activeStores.value), delta: compareText(h.activeStores.value, h.activeStores.prev, r.prevMonthShort, String, 'count') },
    { label: 'New stores', value: String(h.newStores.value), delta: compareText(h.newStores.value, h.newStores.prev, r.prevMonthShort, String, 'count') },
    { label: 'Total sales', value: money(h.sales.value), delta: compareText(h.sales.value, h.sales.prev, r.prevMonthShort, money, 'money') },
    { label: 'Pairs sold', value: String(h.pairs.value), delta: compareText(h.pairs.value, h.pairs.prev, r.prevMonthShort, String, 'pairs') },
    { label: 'Xocks revenue', value: money(h.xocksRevenue.value), delta: compareText(h.xocksRevenue.value, h.xocksRevenue.prev, r.prevMonthShort, money, 'money') },
    {
      label: 'Invoices',
      value: `${h.invoicesPaid} paid · ${h.invoicesPending} pending`,
      note: { text: `${fmtRM(h.pendingRm)} still to collect by ${r.paymentDueLabel}`, tone: 'amber' },
    },
  ]

  s.text('Headline numbers', MX, s.y, { size: 13, font: s.bold, color: C.black })
  s.text(`Compared with ${r.prevMonthLabel}`, MX, s.y - 14, { size: 8, color: C.grey })
  s.y -= 30

  const gap = 10
  const cardW = (CW - gap * 2) / 3
  const cardH = 66
  cards.forEach((c, i) => {
    const col = i % 3
    const row = Math.floor(i / 3)
    const x = MX + col * (cardW + gap)
    const top = s.y - row * (cardH + gap)
    s.rect(x, top - cardH, cardW, cardH, C.card)
    s.text(c.label, x + 12, top - 16, { size: 8, color: C.grey })
    const valueSize = c.note ? 12.5 : 16
    s.text(c.value, x + 12, top - 37, { size: valueSize, font: s.bold, color: C.black })
    if (c.delta) {
      const tone = c.delta.dir === 'up' ? C.green : c.delta.dir === 'down' ? C.amber : C.grey
      s.arrow(x + 12, top - 45, c.delta.dir, tone)
      s.text(c.delta.text, x + 23, top - 52, { size: 7.5, color: tone })
    }
    if (c.note) {
      s.text(c.note.text, x + 12, top - 52, { size: 7.5, color: TONE[c.note.tone].solid })
    }
  })
  s.y -= 2 * cardH + gap + 22
}

function drawBands(s: Sheet, r: MonthlyReport) {
  s.text(`Stores by sales in ${r.monthLabel.split(' ')[0]}`, MX, s.y, { size: 13, font: s.bold, color: C.black })
  s.text('Number of stores and sales in each list', MX, s.y - 14, { size: 8, color: C.grey })
  s.y -= 30

  const maxTotal = Math.max(0, ...r.bands.map((b) => b.total))
  const trackX = MX + 210
  const trackW = 200
  for (const band of r.bands) {
    const h = 46
    const top = s.y
    s.rect(MX, top - h, CW, h, TONE[band.tone].tint)
    s.rect(MX, top - h, 5, h, TONE[band.tone].solid)
    s.text(band.label, MX + 16, top - 19, { size: 12, font: s.bold, color: C.black })
    s.text(plural(band.stores.length, 'store'), MX + 16, top - 33, { size: 8, color: C.grey })
    s.rect(trackX, top - 26, trackW, 9, C.track)
    const fillW = maxTotal > 0 ? (band.total / maxTotal) * trackW : 0
    if (fillW > 0) s.rect(trackX, top - 26, fillW, 9, TONE[band.tone].solid)
    s.rightText(fmtRM(band.total), MX + CW - 12, top - 26, { size: 12, font: s.bold, color: C.black })
    s.y -= h + 8
  }
  s.y -= 14
}

function drawCategories(s: Sheet, r: MonthlyReport) {
  s.ensure(60)
  s.text('Sales by store category', MX, s.y, { size: 13, font: s.bold, color: C.black })
  s.text(`Stores in each store type, ${r.monthLabel}`, MX, s.y - 14, { size: 8, color: C.grey })
  s.y -= 34

  const colStores = MX + 165
  const barX = MX + 185
  const barW = 150
  const colTotal = MX + 400
  const colAvg = MX + CW
  s.text('CATEGORY', MX, s.y, { size: 7, font: s.bold, color: C.grey })
  s.rightText('STORES', colStores, s.y, { size: 7, font: s.bold, color: C.grey })
  s.rightText('TOTAL · AVG PER STORE', colAvg, s.y, { size: 7, font: s.bold, color: C.grey })
  s.y -= 8
  s.rect(MX, s.y, CW, 0.8, C.grey)
  s.y -= 12

  const maxTotal = Math.max(0, ...r.categories.map((c) => c.total))
  for (const c of r.categories) {
    s.ensure(18)
    s.text(s.fit(c.label, 170, 9), MX, s.y, { size: 9, color: C.ink })
    s.rightText(String(c.stores), colStores, s.y, { size: 9, color: C.ink })
    s.rect(barX, s.y - 1, barW, 7, C.track)
    const w = maxTotal > 0 ? (c.total / maxTotal) * barW : 0
    if (w > 0) s.rect(barX, s.y - 1, w, 7, C.black)
    s.rightText(fmtRM(c.total), colTotal, s.y, { size: 9, font: s.bold, color: C.black })
    s.rightText(fmtRM(c.average), colAvg, s.y, { size: 8, color: C.grey })
    s.y -= 18
  }
  if (r.categories.length === 0) {
    s.text('No stores in scope this month.', MX, s.y, { size: 9, color: C.grey })
    s.y -= 18
  }
}

// ── Page 2 ──────────────────────────────────────────────────────────────────

function drawActionCard(s: Sheet, card: ActionCard) {
  const rows = card.rows.length > 0 ? card.rows : null
  const h = 36 + (rows ? rows.length * 15 : 16) + 8
  s.ensure(h + 10)
  const top = s.y
  const tone = TONE[card.tone]
  s.rect(MX, top - h, CW, h, tone.tint)
  s.rect(MX, top - h, 5, h, tone.solid)

  const badgeSize = 7
  const badgeW = s.width(card.badge, badgeSize, s.bold) + 12
  s.rect(MX + 16, top - 20, badgeW, 14, tone.solid)
  s.text(card.badge, MX + 22, top - 15.5, { size: badgeSize, font: s.bold, color: C.white })
  s.text(s.fit(card.title, CW - badgeW - 180, 10.5, s.bold), MX + 16 + badgeW + 10, top - 16, { size: 10.5, font: s.bold, color: C.black })
  s.rightText(plural(card.rows.length, 'store'), MX + CW - 12, top - 16, { size: 8, color: C.grey })

  if (!rows) {
    s.text('None this month.', MX + 16, top - 38, { size: 8.5, color: C.grey })
    s.y = top - h - 10
    return
  }

  let y = top - 38
  for (const r of rows) {
    const name = s.fit(r.name, 245, 9)
    s.text(name, MX + 16, y, { size: 9, color: C.ink })
    if (r.onPlan) {
      const nameW = s.width(name, 9)
      s.text('4-month plan', MX + 16 + nameW + 6, y, { size: 6.5, font: s.bold, color: C.green })
    }
    s.text(s.fit(r.category, 130, 8), MX + 270, y, { size: 8, color: C.grey })
    s.rightText(r.metric, MX + CW - 12, y, { size: 9, font: s.bold, color: tone.solid })
    y -= 15
  }
  s.y = top - h - 10
}

function drawActionPlan(s: Sheet, r: MonthlyReport) {
  s.text('Action plan', MX, s.y, { size: 13, font: s.bold, color: C.black })
  s.text('Red = act now · Amber = this week · Green = keep it going', MX, s.y - 14, { size: 8, color: C.grey })
  s.y -= 32
  for (const card of r.actions) drawActionCard(s, card)
}

// ── Page 3 ──────────────────────────────────────────────────────────────────

function drawStoreList(s: Sheet, title: string, tone: ActionTone, stores: ReportStore[], total: number) {
  s.ensure(60)
  s.rect(MX, s.y - 12, 4, 14, TONE[tone].solid)
  s.text(title, MX + 12, s.y, { size: 12, font: s.bold, color: C.black })
  s.rightText(`${plural(stores.length, 'store')} · ${fmtRM(total)}`, MX + CW, s.y + 1, { size: 9, color: C.grey })
  s.y -= 20

  const cols = { code: MX, name: MX + 62, cat: MX + 262, city: MX + 372, sales: MX + CW }
  const head = (label: string, x: number) => s.text(label, x, s.y, { size: 7, font: s.bold, color: C.grey })
  head('CODE', cols.code)
  head('STORE', cols.name)
  head('CATEGORY', cols.cat)
  head('CITY', cols.city)
  s.rightText('SEP SALES', cols.sales, s.y, { size: 7, font: s.bold, color: C.grey })
  s.y -= 6
  s.rect(MX, s.y, CW, 0.6, C.grey)
  s.y -= 11

  if (stores.length === 0) {
    s.text('No stores in this list.', MX, s.y, { size: 8.5, color: C.grey })
    s.y -= 16
  }
  for (const st of stores) {
    s.ensure(16)
    s.text(st.code, cols.code, s.y, { size: 7.5, color: C.grey })
    const name = s.fit(st.name, 196, 8.5)
    s.text(name, cols.name, s.y, { size: 8.5, color: C.ink })
    if (st.onPlan) {
      s.text('4-month plan', cols.name + s.width(name, 8.5) + 6, s.y, { size: 6.5, font: s.bold, color: C.green })
    }
    s.text(s.fit(st.category, 104, 7.5), cols.cat, s.y, { size: 7.5, color: C.grey })
    s.text(s.fit(st.city, 136, 7.5), cols.city, s.y, { size: 7.5, color: C.grey })
    s.rightText(st.sales > 0 ? fmtRM(st.sales) : 'No sales', cols.sales, s.y, {
      size: 8.5, font: s.bold, color: st.sales > 0 ? C.black : C.red,
    })
    s.y -= 15
  }
  s.y -= 12
}

function drawNewStores(s: Sheet, r: MonthlyReport) {
  s.ensure(60)
  s.text('New stores this month', MX, s.y, { size: 12, font: s.bold, color: C.black })
  s.y -= 18
  if (r.newStores.length === 0) {
    s.text('No new stores were opened this month.', MX, s.y, { size: 8.5, color: C.grey })
    return
  }
  for (const n of r.newStores) {
    const h = 52
    s.ensure(h + 8)
    const top = s.y
    s.rect(MX, top - h, CW, h, C.card)
    s.text(`${n.name}  ·  ${n.code}`, MX + 12, top - 17, { size: 10, font: s.bold, color: C.black })
    const first = n.firstSaleDate ? `First sale ${dayLabel(n.firstSaleDate)}` : 'No sale yet'
    s.text(
      s.fit(`${n.category} · ${n.city || 'City not set'} · Opened ${dayLabel(n.openedOn)} · Starter stock ${n.starterStock} pairs · ${first}`, CW - 24, 8, s.regular),
      MX + 12, top - 33, { size: 8, color: C.grey },
    )
    s.text(
      `Opened by: ${n.openedBy ?? 'not recorded (stores opened from now on will show the team member)'}`,
      MX + 12, top - 45, { size: 8, color: C.grey },
    )
    s.y = top - h - 8
  }
}

export async function generateMonthlyReportPdf(report: MonthlyReport): Promise<Uint8Array> {
  const doc = await PDFDocument.create()
  doc.setTitle(`XCMS Monthly Report ${report.monthLabel}`)
  doc.setAuthor('XCMS')
  const regular = await doc.embedFont(StandardFonts.Helvetica)
  const bold = await doc.embedFont(StandardFonts.HelveticaBold)
  const s = new Sheet(doc, regular, bold, report)

  s.newPage('Headline numbers and where every store sits')
  drawHeadline(s, report)
  drawBands(s, report)
  drawCategories(s, report)

  s.newPage('Action plan — what to do this month')
  drawActionPlan(s, report)

  s.newPage('Store lists with category, and new stores')
  for (const band of report.bands) {
    drawStoreList(s, band.label, band.tone, band.stores, band.total)
  }
  drawNewStores(s, report)

  s.finish()
  return doc.save()
}
